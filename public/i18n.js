export const LANGUAGE_STORAGE_KEY = "sibercraft-language";

export function loadLanguage(storage = localStorage) {
  const saved = storage.getItem(LANGUAGE_STORAGE_KEY);
  return saved === "id" ? "id" : "en";
}

export function saveLanguage(language, storage = localStorage) {
  storage.setItem(LANGUAGE_STORAGE_KEY, language === "id" ? "id" : "en");
}

export function translate(language, key, vars = {}) {
  const current = language === "id" ? "id" : "en";
  const table = translations[current] || translations.en;
  const template = table[key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}
